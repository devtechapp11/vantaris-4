// Copies the deterministic finance engine and the Deal Brief schema into
// supabase/functions/_shared so the Edge Functions run the exact same code as
// the app. `--check` fails (for CI) when the copies are out of date.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'supabase/functions/_shared');
const FILES = [
  ['src/lib/finance/core.ts', 'core.ts'],
  ['src/lib/finance/rng.ts', 'rng.ts'],
  ['src/lib/finance/templates.ts', 'templates.ts'],
  ['src/lib/finance/elo.ts', 'elo.ts'],
  ['src/pedagogy/dealBrief.ts', 'dealBrief.ts'],
  ['src/lib/exercises/schema.ts', 'exercise-schema.ts'],
  ['src/lib/exercises/lesson.ts', 'lesson.ts'],
];
const HEADER = '// Generated by scripts/sync-shared.mjs from the app sources. Do not edit.\n';
const deno = (src) => HEADER + src
  .replace("from 'zod'", "from 'npm:zod@3.25.76'")
  .replace("from '../finance/templates.ts'", "from './templates.ts'")
  .replace("from './schema.ts'", "from './exercise-schema.ts'");

const check = process.argv.includes('--check');
let stale = 0;
mkdirSync(out, { recursive: true });
for (const [from, to] of FILES) {
  const want = deno(readFileSync(join(root, from), 'utf8'));
  const dest = join(out, to);
  const have = existsSync(dest) ? readFileSync(dest, 'utf8') : '';
  if (have === want) continue;
  stale += 1;
  if (check) console.error(`sync-shared: ${to} is out of date (run node scripts/sync-shared.mjs)`);
  else writeFileSync(dest, want);
}
if (check && stale) process.exit(1);
console.log(check ? 'sync-shared: Edge Function copies are up to date.' : `sync-shared: ${stale} file(s) written.`);
